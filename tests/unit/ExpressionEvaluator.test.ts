import { describe, it } from "node:test";
import assert from "node:assert/strict";
import { evaluate, formatDecimal } from "../../src/tools/ExpressionEvaluator.js";

/**
 * Asserts that two numbers are approximately equal (for floating-point safety).
 */
function assertApprox(actual: number, expected: number, epsilon = 1e-9): void {
  assert.ok(
    Math.abs(actual - expected) < epsilon,
    `Expected ${actual} to approximately equal ${expected} (within ${epsilon})`,
  );
}

describe("ExpressionEvaluator", () => {
  // ==========================================================================
  // 基本四则运算
  // ==========================================================================
  describe("基本四则运算", () => {
    it("1+2 = 3", () => {
      assert.equal(evaluate("1+2").result, 3);
    });

    it("10-3 = 7", () => {
      assert.equal(evaluate("10-3").result, 7);
    });

    it("4*5 = 20", () => {
      assert.equal(evaluate("4*5").result, 20);
    });

    it("20/4 = 5", () => {
      assert.equal(evaluate("20/4").result, 5);
    });
  });

  // ==========================================================================
  // 运算符优先级
  // ==========================================================================
  describe("运算符优先级", () => {
    it("2+3*4 = 14 (乘法优先于加法)", () => {
      assert.equal(evaluate("2+3*4").result, 14);
    });

    it("(2+3)*4 = 20 (括号改变优先级)", () => {
      assert.equal(evaluate("(2+3)*4").result, 20);
    });
  });

  // ==========================================================================
  // 括号嵌套
  // ==========================================================================
  describe("括号嵌套", () => {
    it("((1+2)*3) = 9", () => {
      assert.equal(evaluate("((1+2)*3)").result, 9);
    });

    it("(1+2)*(3+4) = 21", () => {
      assert.equal(evaluate("(1+2)*(3+4)").result, 21);
    });
  });

  // ==========================================================================
  // 小数运算
  // ==========================================================================
  describe("小数运算", () => {
    it("0.1+0.2 approx 0.3 (浮点近似)", () => {
      assertApprox(evaluate("0.1+0.2").result, 0.3);
    });

    it("3.14*2 = 6.28", () => {
      assertApprox(evaluate("3.14*2").result, 6.28);
    });
  });

  // ==========================================================================
  // 千分位分隔符
  // ==========================================================================
  describe("千分位分隔符", () => {
    it("1,234.56+100 = 1334.56", () => {
      assertApprox(evaluate("1,234.56+100").result, 1334.56);
    });

    it("1,000,000/1000 = 1000", () => {
      assert.equal(evaluate("1,000,000/1000").result, 1000);
    });
  });

  // ==========================================================================
  // 百分号
  // ==========================================================================
  describe("百分号", () => {
    it("50% = 0.5", () => {
      assert.equal(evaluate("50%").result, 0.5);
    });

    it("100+10% = 100.1", () => {
      assertApprox(evaluate("100+10%").result, 100.1);
    });
  });

  // ==========================================================================
  // 会计负数表示法
  // ==========================================================================
  describe("会计负数表示法", () => {
    it("(123.45) = -123.45", () => {
      assertApprox(evaluate("(123.45)").result, -123.45);
    });

    // 注意: (100) 不含小数点或单位后缀，不会被识别为会计负数，
    // 而是被当作普通括号表达式 (100) = 100。
    // 使用 (100.00) 来测试会计负数功能。
    it("(100.00) + 200 = 100 (含小数点的会计负数)", () => {
      assert.equal(evaluate("(100.00) + 200").result, 100);
    });
  });

  // ==========================================================================
  // 单位后缀
  // ==========================================================================
  describe("单位后缀", () => {
    it("100万 = 1000000", () => {
      assert.equal(evaluate("100万").result, 1000000);
    });

    it("5千元 = 5000", () => {
      assert.equal(evaluate("5千元").result, 5000);
    });

    it("10元 = 10 (元为无操作后缀)", () => {
      assert.equal(evaluate("10元").result, 10);
    });
  });

  // ==========================================================================
  // 全角字符规范化
  // ==========================================================================
  describe("全角字符规范化", () => {
    it("１＋２ = 3 (全角数字与运算符)", () => {
      assert.equal(evaluate("１＋２").result, 3);
    });

    it("１００＝１００ 应报错 (全角等号不支持)", () => {
      assert.throws(() => evaluate("１００＝１００"), /unsupported character/i);
    });

    it("１，２３４ = 1234 (全角逗号)", () => {
      assert.equal(evaluate("１，２３４").result, 1234);
    });

    it("１．５ = 1.5 (全角句号)", () => {
      assert.equal(evaluate("１．５").result, 1.5);
    });

    it("５０％ = 0.5 (全角百分号)", () => {
      assert.equal(evaluate("５０％").result, 0.5);
    });

    it("１　＋　２ = 3 (全角空格忽略)", () => {
      assert.equal(evaluate("１　＋　２").result, 3);
    });
  });

  // ==========================================================================
  // 货币符号忽略
  // ==========================================================================
  describe("货币符号忽略", () => {
    it("¥100 = 100", () => {
      assert.equal(evaluate("¥100").result, 100);
    });

    it("￥200 = 200", () => {
      assert.equal(evaluate("￥200").result, 200);
    });
  });

  // ==========================================================================
  // Dash 字符作为零
  // ==========================================================================
  describe("Dash 字符作为零", () => {
    it("– + 5 = 5 (en-dash)", () => {
      assert.equal(evaluate("\u2013 + 5").result, 5);
    });

    it("— * 3 = 0 (em-dash)", () => {
      assert.equal(evaluate("\u2014 * 3").result, 0);
    });
  });

  // ==========================================================================
  // 一元运算符
  // ==========================================================================
  describe("一元运算符", () => {
    it("-5 = -5", () => {
      assert.equal(evaluate("-5").result, -5);
    });

    it("+3 = 3", () => {
      assert.equal(evaluate("+3").result, 3);
    });

    it("--5 = 5 (双重负号)", () => {
      assert.equal(evaluate("--5").result, 5);
    });
  });

  // ==========================================================================
  // 错误处理
  // ==========================================================================
  describe("错误处理", () => {
    it("除以零应报错", () => {
      assert.throws(() => evaluate("1/0"), /Division by zero/i);
    });

    it("空表达式应报错", () => {
      assert.throws(() => evaluate(""), /empty/i);
    });

    it("纯空格表达式应报错", () => {
      assert.throws(() => evaluate("   "), /empty/i);
    });

    it("过长表达式应报错 (>8000字符)", () => {
      const longExpr = "1+".repeat(4001) + "1"; // 8003 chars
      assert.throws(() => evaluate(longExpr), /too long/i);
    });

    it("不支持的字符应报错", () => {
      assert.throws(() => evaluate("1=2"), /unsupported character/i);
    });

    it("缺少右括号应报错", () => {
      assert.throws(() => evaluate("(1+2"), /Missing closing parenthesis/i);
    });
  });

  // ==========================================================================
  // formatDecimal
  // ==========================================================================
  describe("formatDecimal", () => {
    it("formatDecimal(0.5) = '0.5'", () => {
      assert.equal(formatDecimal(0.5), "0.5");
    });

    it("formatDecimal(100) = '100'", () => {
      assert.equal(formatDecimal(100), "100");
    });

    it("formatDecimal(3.14) = '3.14'", () => {
      assert.equal(formatDecimal(3.14), "3.14");
    });
  });

  // ==========================================================================
  // 复合表达式
  // ==========================================================================
  describe("复合表达式", () => {
    it("1,234.56 - 200.00 * 3 = 634.56", () => {
      assertApprox(evaluate("1,234.56 - 200.00 * 3").result, 634.56);
    });

    it("(100万 + 50万) * 2% = 30000", () => {
      assertApprox(evaluate("(100万 + 50万) * 2%").result, 30000);
    });
  });

  // ==========================================================================
  // normalizedExpression 正确性
  // ==========================================================================
  describe("normalizedExpression 正确性", () => {
    it("'1+2' normalizes to '1 + 2'", () => {
      assert.equal(evaluate("1+2").normalizedExpression, "1 + 2");
    });

    it("'1,234.56' normalizes to '1234.56' (逗号移除)", () => {
      assert.equal(evaluate("1,234.56").normalizedExpression, "1234.56");
    });

    it("'(123.45)' normalizes to '(-123.45)' (会计负数)", () => {
      assert.equal(evaluate("(123.45)").normalizedExpression, "(-123.45)");
    });

    it("'50%' normalizes to '0.5'", () => {
      assert.equal(evaluate("50%").normalizedExpression, "0.5");
    });

    it("'100万' normalizes to '1000000'", () => {
      assert.equal(evaluate("100万").normalizedExpression, "1000000");
    });
  });
});
