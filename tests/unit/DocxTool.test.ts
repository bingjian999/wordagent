describe("DocxService — parse", () => {
  it("should parse a generated .docx file", async () => {
    // First generate a document
    const genResult = await service.generate({
      title: "Parse Test",
      paragraphs: [
        { text: "Revenue Report", heading: "Heading1" },
        { text: "Total revenue: ¥1,234,567" },
        { text: "Net profit: ¥246,913" },
      ],
    });
    assert.ok(genResult.ok, "Generate should succeed for parse test");

    if (genResult.ok) {
      // Now parse it
      const parseResult = await service.parse(genResult.value.buffer);
      assert.ok(parseResult.ok, "Parse should succeed");
      if (parseResult.ok) {
        assert.ok(parseResult.value.text.length > 0, "Extracted text should not be empty");
        assert.ok(parseResult.value.charCount > 0, "Character count should be positive");
        assert.ok(
          parseResult.value.text.includes("Revenue Report") ||
          parseResult.value.text.includes("revenue") ||
          parseResult.value.text.includes("Parse Test"),
          "Extracted text should contain document content",
        );
      }
    }
  });

  it("should parse a .docx file from disk", async () => {
    // Generate and save
    const filePath = path.join(tempDir, "parse-test.docx");
    await service.generateToFile(
      {
        title: "File Parse Test",
        paragraphs: [
          { text: "This is a test document for file parsing." },
          { text: "It contains multiple paragraphs." },
        ],
      },
      filePath,
    );

    // Parse from file
    const result = await service.parseFile(filePath);
    assert.ok(result.ok, "Parse file should succeed");
    if (result.ok) {
      assert.ok(result.value.text.length > 0, "Extracted text should not be empty");
    }
  });

  it("should return error for non-existent file", async () => {
    const result = await service.parseFile(path.join(tempDir, "nonexistent.docx"));
    assert.ok(!result.ok, "Parse non-existent file should fail");
    if (!result.ok) {
      assert.ok(result.error.includes("Failed to read file"), "Error should mention file read failure");
    }
  });

  it("should return error for invalid buffer", async () => {
    const result = await service.parse(Buffer.from("not a docx file"));
    assert.ok(!result.ok, "Parse invalid buffer should fail");
    if (!result.ok) {
      assert.ok(result.error.includes("Failed to parse"), "Error should mention parse failure");
    }
  });
});

describe("DocxService — round-trip", () => {
  it("should generate → parse → verify content", async () => {
    const originalContent = {
      title: "Round-Trip Test",
      paragraphs: [
        { text: "Financial Summary", heading: "Heading1" as const },
        { text: "Total Revenue: ¥4,484,567" },
        { text: "Total Cost: ¥3,287,654" },
        { text: "Net Profit: ¥1,196,913" },
      ],
      tables: [
        {
          rows: [
            ["Quarter", "Revenue", "Cost", "Net"],
            ["Q1", "1,234,567", "987,654", "246,913"],
            ["Q2", "1,500,000", "1,100,000", "400,000"],
            ["Q3", "1,750,000", "1,200,000", "550,000"],
          ],
          headerRow: true,
        },
      ],
    };

    // Generate
    const genResult = await service.generate(originalContent);
    assert.ok(genResult.ok, "Generate should succeed");

    if (genResult.ok) {
      // Parse
      const parseResult = await service.parse(genResult.value.buffer);
      assert.ok(parseResult.ok, "Parse should succeed");

      if (parseResult.ok) {
        const text = parseResult.value.text;
        // Verify key content is present in extracted text
        assert.ok(text.includes("Round-Trip Test") || text.includes("Financial Summary"), "Title or heading should be in text");
        assert.ok(text.includes("4,484,567") || text.includes("Revenue"), "Revenue should be in text");
      }
    }
  });
});

describe("DocxTool", () => {
  it("should generate a .docx file via tool", async () => {
    const outputPath = path.join(tempDir, "tool-generate.docx");
    const result = await tool.execute({
      operation: "generate",
      filePath: outputPath,
      title: "Tool Generated Report",
      paragraphs: [
        { text: "Executive Summary", heading: "Heading1" },
        { text: "This report was generated by the DocxTool." },
        { text: "It demonstrates the tool interface." },
      ],
      tables: [
        {
          rows: [
            ["Metric", "Value"],
            ["Revenue", "¥1,234,567"],
            ["Growth", "15.3%"],
          ],
          headerRow: true,
        },
      ],
    });

    assert.ok(result.success, "Tool generate should succeed");
    assert.equal(result.operation, "generate");
    assert.ok(result.filePath, "File path should be set");
    assert.ok(result.size! > 0, "Size should be positive");

    // Verify file exists
    const stat = await fs.stat(outputPath);
    assert.ok(stat.size > 0, "File should exist on disk");
  });

  it("should parse a .docx file via tool", async () => {
    // First generate
    const filePath = path.join(tempDir, "tool-parse.docx");
    await tool.execute({
      operation: "generate",
      filePath,
      title: "Parse Test Document",
      paragraphs: [
        { text: "This document will be parsed." },
        { text: "It contains text for extraction." },
      ],
    });

    // Now parse
    const result = await tool.execute({
      operation: "parse",
      filePath,
    });

    assert.ok(result.success, "Tool parse should succeed");
    assert.equal(result.operation, "parse");
    assert.ok(result.text!.length > 0, "Extracted text should not be empty");
    assert.ok(result.charCount! > 0, "Character count should be positive");
  });

  it("should fail when generating without paragraphs or tables", async () => {
    const result = await tool.execute({
      operation: "generate",
      filePath: path.join(tempDir, "empty.docx"),
    });

    assert.ok(!result.success, "Should fail without content");
    assert.ok(result.message.includes("paragraph or table"), "Error should mention missing content");
  });

  it("should fail when parsing non-existent file", async () => {
    const result = await tool.execute({
      operation: "parse",
      filePath: path.join(tempDir, "does-not-exist.docx"),
    });

    assert.ok(!result.success, "Should fail for non-existent file");
    assert.ok(result.message.includes("Failed"), "Error should mention failure");
  });

  it("should fail for unknown operation", async () => {
    const result = await tool.execute({
      operation: "unknown" as "parse",
      filePath: "test.docx",
    });

    assert.ok(!result.success, "Should fail for unknown operation");
    assert.ok(result.message.includes("Unknown operation"), "Error should mention unknown operation");
  });

  it("should fail when filePath is empty for parse", async () => {
    const result = await tool.execute({
      operation: "parse",
      filePath: "",
    });

    assert.ok(!result.success, "Should fail with empty filePath");
    assert.ok(result.message.includes("required"), "Error should mention required");
  });

  it("should generate with only tables (no paragraphs)", async () => {
    const result = await tool.execute({
      operation: "generate",
      filePath: path.join(tempDir, "tables-only.docx"),
      tables: [
        {
          rows: [
            ["Name", "Value"],
            ["A", "1"],
            ["B", "2"],
          ],
          headerRow: true,
        },
      ],
    });

    assert.ok(result.success, "Should succeed with only tables");
  });
});
