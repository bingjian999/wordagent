import { describe, it, before, after } from "node:test";
import assert from "node:assert/strict";
import * as fs from "node:fs/promises";
import * as path from "node:path";
import * as os from "node:os";
import { DocxService } from "../../src/services/docx/DocxService.js";
import { DocxTool } from "../../src/tools/DocxTool.js";

let tempDir: string;
let service: DocxService;
let tool: DocxTool;

before(async () => {
  tempDir = path.join(os.tmpdir(), `wordagent-docx-test-${Date.now()}`);
  await fs.mkdir(tempDir, { recursive: true });
  service = new DocxService();
  tool = new DocxTool();
});

after(async () => {
  try {
    await fs.rm(tempDir, { recursive: true, force: true });
  } catch {
    // Windows sometimes locks files
  }
});

